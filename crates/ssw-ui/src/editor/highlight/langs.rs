use super::engine::{Attr, BASE, Interp, KeyStyle, Spec, StrRule};

const fn rule(open: &'static str, close: &'static str, escape: bool, multiline: bool) -> StrRule {
    StrRule {
        open,
        close,
        escape,
        multiline,
        doubled: false,
        interp: Interp::No,
    }
}

